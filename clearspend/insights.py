"""Turn the SQL views into a written findings report (docs/findings.md).

Every number in the report is pulled from the database when the pipeline runs,
so the write-up can't drift away from the data.
"""

import pandas as pd

import re

from .clean import ACCOUNTING, INDIVIDUAL, NO_VENDOR, NOT_REPORTED

SMALL_WORDS = {"And", "Of", "The", "For", "In", "At", "To", "On"}
KEEP_UPPER = {"Va": "VA", "Usa": "USA", "Llc": "LLC", "Dmas": "DMAS", "Doa": "DOA", "Vdot": "VDOT", "Abc": "ABC"}


def nice(name):
    """'HEALTH AND HUMAN RESOURCES' -> 'Health and Human Resources'."""
    words = str(name).title().split()
    out = []
    for i, w in enumerate(words):
        if i and w in SMALL_WORDS:
            w = w.lower()
        out.append(KEEP_UPPER.get(w, w))
    return re.sub(r"'S\b", "'s", " ".join(out))


def money(x):
    x = float(x)
    sign = "-" if x < 0 else ""
    x = abs(x)
    if x >= 1e9:
        return f"{sign}${x / 1e9:,.2f}B"
    if x >= 1e6:
        return f"{sign}${x / 1e6:,.1f}M"
    return f"{sign}${x:,.0f}"


def change_pct(current, prior):
    """Percent change, or n/a when the prior year is too small for a percent to mean anything."""
    return pd.Series([c / p - 1 if p >= 1e6 else float("nan") for c, p in zip(current, prior)], index=current.index)


def pct(x):
    return "n/a" if pd.isna(x) else f"{x:+.1%}"


def table(df, columns):
    head = "| " + " | ".join(columns) + " |"
    rule = "|" + "|".join("---" for _ in columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, rule, *rows])


def months_by_year(con):
    q = "SELECT fiscal_year, COUNT(DISTINCT substr(month, 1, 7)) FROM fact_monthly GROUP BY 1"
    return dict(con.execute(q).fetchall())


def matching_month_totals(con, year):
    """Agency totals for `year` and the year before, using only the months both years have."""
    months = pd.read_sql("SELECT DISTINCT fiscal_year, substr(month, 6, 2) AS mm FROM fact_monthly", con)
    have = set(months.loc[months.fiscal_year == year, "mm"])
    prior = set(months.loc[months.fiscal_year == year - 1, "mm"])
    shared = sorted(have & prior)
    marks = ",".join(f"'{m}'" for m in shared)
    df = pd.read_sql(
        f"""
        SELECT a.agency, f.fiscal_year, SUM(f.amount) AS spend
        FROM fact_monthly f JOIN dim_agency a ON a.agency_id = f.agency_id
        WHERE f.fiscal_year IN (?, ?) AND substr(f.month, 6, 2) IN ({marks})
        GROUP BY a.agency, f.fiscal_year
        """, con, params=(year - 1, year))
    wide = df.pivot_table(index="agency", columns="fiscal_year", values="spend", aggfunc="sum").fillna(0)
    wide.columns = ["prior", "current"]
    wide["change"] = wide["current"] - wide["prior"]
    return wide.reset_index(), len(shared)


def build_report(con, quality):
    months = months_by_year(con)
    years = sorted(months)
    full = [y for y in years if months[y] == 12]
    latest_full = full[-1]
    partial = [y for y in years if months[y] < 12]
    out = []

    totals = pd.read_sql("SELECT fiscal_year, SUM(total_spend) AS spend FROM v_agency_year GROUP BY 1", con)
    totals = dict(zip(totals.fiscal_year, totals.spend))

    out.append("# ClearSpend VA findings\n")
    out.append(
        "Generated by `run.py` from Virginia's Commonwealth Data Point expenditure files. "
        "All figures are net of refunds and reversals. Fiscal years run July 1 to June 30.\n")

    # --- headline
    out.append("## The big picture\n")
    if latest_full - 1 in totals:
        prev = totals[latest_full - 1]
        cur = totals[latest_full]
        out.append(
            f"- Virginia state agencies spent **{money(cur)}** in FY{latest_full}, "
            f"{pct(cur / prev - 1)} from {money(prev)} in FY{latest_full - 1}.")
    for y in partial:
        ytd, n = matching_month_totals(con, y)
        cur, prev = ytd["current"].sum(), ytd["prior"].sum()
        out.append(
            f"- FY{y} only has {months[y]} months published so far. Over those same {n} months, spending was "
            f"**{money(cur)}**, {pct(cur / prev - 1)} compared to the same months of FY{y - 1}.")
    sec = pd.read_sql(
        "SELECT secretariat, total_spend, share_of_year FROM v_secretariat_year WHERE fiscal_year = ? "
        "ORDER BY total_spend DESC", con, params=(latest_full,))
    top2 = sec.head(2)
    out.append(
        f"- {nice(top2.iloc[0].secretariat)} and {nice(top2.iloc[1].secretariat)} together made up "
        f"**{top2.share_of_year.sum():.0%}** of FY{latest_full} spending.")
    cat = pd.read_sql(
        "SELECT category, total_spend, share_of_year FROM v_category_year WHERE fiscal_year = ? "
        "ORDER BY total_spend DESC", con, params=(latest_full,))
    out.append(
        f"- By type of spending, the largest buckets were {cat.iloc[0].category.lower()} "
        f"({cat.iloc[0].share_of_year:.0%}), {cat.iloc[1].category.lower()} ({cat.iloc[1].share_of_year:.0%}) "
        f"and {cat.iloc[2].category.lower()} ({cat.iloc[2].share_of_year:.0%}).\n")
    out.append("![Spending by secretariat](img/spend_by_secretariat.png)\n")

    # --- top agencies
    out.append(f"## Top 10 agencies, FY{latest_full}\n")
    top = pd.read_sql(
        """SELECT agency, secretariat, total_spend, pct_change FROM v_agency_yoy
           WHERE fiscal_year = ? ORDER BY total_spend DESC LIMIT 10""", con, params=(latest_full,))
    top["secretariat"] = top["secretariat"].map(nice)
    top["total_spend"] = top["total_spend"].map(money)
    top["pct_change"] = top["pct_change"].map(pct)
    out.append(table(top, ["Agency", "Secretariat", f"FY{latest_full}", "Change vs prior year"]) + "\n")

    # --- biggest movers
    out.append(f"## Biggest changes, FY{latest_full - 1} to FY{latest_full}\n")
    yoy = pd.read_sql(
        "SELECT agency, prior_year_spend, total_spend, change, pct_change FROM v_agency_yoy "
        "WHERE fiscal_year = ? AND prior_year_spend IS NOT NULL", con, params=(latest_full,))
    for label, frame in [("Largest increases", yoy.nlargest(5, "change")),
                         ("Largest decreases", yoy.nsmallest(5, "change"))]:
        frame = frame.assign(pct_change=change_pct(frame.total_spend, frame.prior_year_spend))
        frame = frame.assign(
            prior_year_spend=frame.prior_year_spend.map(money), total_spend=frame.total_spend.map(money),
            change=frame.change.map(money), pct_change=frame["pct_change"].map(pct))
        out.append(f"**{label}**\n")
        out.append(table(frame, ["Agency", f"FY{latest_full - 1}", f"FY{latest_full}", "Change", "%"]) + "\n")
    out.append("![Biggest changes](img/biggest_changes.png)\n")

    for y in partial:
        ytd, n = matching_month_totals(con, y)
        out.append(f"## FY{y} so far ({n} months vs the same months of FY{y - 1})\n")
        for label, frame in [("Growing fastest in dollars", ytd.nlargest(5, "change")),
                             ("Shrinking most in dollars", ytd.nsmallest(5, "change"))]:
            frame = frame.assign(pct=change_pct(frame.current, frame.prior))
            frame = frame[["agency", "prior", "current", "change", "pct"]].assign(
                prior=frame.prior.map(money), current=frame.current.map(money),
                change=frame.change.map(money), pct=frame.pct.map(pct))
            out.append(f"**{label}**\n")
            out.append(table(frame, ["Agency", f"FY{y - 1}", f"FY{y}", "Change", "%"]) + "\n")

    out.append("## Spending by month\n")
    out.append("![Monthly trend](img/monthly_trend.png)\n")
    trend = pd.read_sql("SELECT month, SUM(total_spend) AS s FROM v_monthly_trend GROUP BY month ORDER BY month", con)
    trend["month"] = pd.to_datetime(trend["month"])
    hi, lo = trend.loc[trend.s.idxmax()], trend.loc[trend.s.idxmin()]
    out.append(
        f"Monthly spending ranged from {money(lo.s)} ({lo.month:%B %Y}) to {money(hi.s)} ({hi.month:%B %Y}), "
        f"with a typical month around {money(trend.s.median())}.\n")

    # --- vendors
    out.append(f"## Largest vendors, FY{latest_full}\n")
    out.append(
        "Only payees that are clearly organizations are ranked. People, payroll and ledger "
        "adjustments are left out (see data notes).\n")
    vend = pd.read_sql(
        "SELECT vendor, total_paid, agencies_paying FROM v_top_vendors WHERE fiscal_year = ? "
        "AND rank_in_year <= 10 ORDER BY rank_in_year", con, params=(latest_full,))
    vend["vendor"] = vend["vendor"].map(nice)
    vend["total_paid"] = vend["total_paid"].map(money)
    out.append(table(vend, ["Vendor", "Paid", "Agencies paying"]) + "\n")

    out.append("## Where one vendor gets most of the money\n")
    conc = pd.read_sql(
        """SELECT agency, vendor_count, vendor_spend, top_vendor_share, hhi FROM v_vendor_concentration
           WHERE fiscal_year = ? AND vendor_spend >= 25000000 AND vendor_count >= 10
           ORDER BY hhi DESC LIMIT 10""",
        con, params=(latest_full,))
    n_high = con.execute(
        "SELECT COUNT(*) FROM v_vendor_concentration WHERE fiscal_year = ? AND vendor_spend >= 25000000 "
        "AND hhi > 2500", (latest_full,)).fetchone()[0]
    n_all = con.execute(
        "SELECT COUNT(*) FROM v_vendor_concentration WHERE fiscal_year = ? AND vendor_spend >= 25000000",
        (latest_full,)).fetchone()[0]
    out.append(
        f"Of the {n_all} agencies that paid at least $25M to outside organizations in FY{latest_full}, "
        f"**{n_high}** were highly concentrated (HHI above 2,500, a common cutoff for a concentrated "
        "market). High concentration isn't automatically a problem, since "
        "some agencies exist to pay one big contractor or managed care plan, but it's where a vendor "
        "change or contract dispute would hurt most. The table skips accounts with fewer than 10 vendors, "
        "since those are mostly pass-through accounts (wire business units, treasury disbursement "
        "accounts) that exist to send money to one place.\n")
    conc = conc.assign(vendor_spend=conc.vendor_spend.map(money), top_vendor_share=conc.top_vendor_share.map(
        lambda s: f"{s:.0%}"), hhi=conc.hhi.map(lambda h: f"{h:,.0f}"))
    out.append(table(conc, ["Agency", "Vendors", "Paid to vendors", "Top vendor share", "HHI"]) + "\n")

    # --- data notes
    out.append("## Data notes\n")
    q = pd.DataFrame(quality).sort_values("file_fiscal_year")
    q = q.assign(
        file_fiscal_year=q.file_fiscal_year.map(lambda y: f"FY{y}"),
        months=q.file_fiscal_year.map(lambda y: months.get(y, "")),
        raw_rows=q.raw_rows.map("{:,}".format), dropped_rows=q.dropped_rows.map("{:,}".format),
        refund_rows=q.refund_rows.map("{:,}".format), individual_rows=q.individual_rows.map("{:,}".format),
        no_vendor_rows=q.no_vendor_rows.map("{:,}".format), adjustment_rows=q.adjustment_rows.map("{:,}".format))
    out.append(table(q[["file_fiscal_year", "months", "raw_rows", "dropped_rows", "refund_rows",
                        "no_vendor_rows", "individual_rows", "adjustment_rows"]],
                     ["Year", "Months", "Transactions", "Unreadable", "Refunds/reversals", "No vendor",
                      "Individual (withheld)", "Ledger adjustments"]) + "\n")
    shares = pd.read_sql(
        """SELECT v.vendor, SUM(f.amount) AS amount FROM fact_vendor_year f
           JOIN dim_vendor v ON v.vendor_id = f.vendor_id WHERE f.fiscal_year = ?
           AND v.vendor IN (?, ?, ?, ?) GROUP BY v.vendor""", con,
        params=(latest_full, NO_VENDOR, INDIVIDUAL, ACCOUNTING, NOT_REPORTED))
    share = dict(zip(shares.vendor, shares.amount / totals[latest_full]))
    out.append(
        f"- **Ledger adjustments.** About {share.get(ACCOUNTING, 0):.0%} of FY{latest_full} dollars carry "
        "\"MISCELLANEOUS ADJUSTMENT\" or \"WARRANT REGISTER\" in the vendor column instead of a real payee. "
        "They count toward agency totals but are left out of vendor rankings.\n"
        f"- **Vendor detail not reported.** About {share.get(NOT_REPORTED, 0):.0%} of dollars, almost all from "
        "the public universities and UVA Medical Center, are listed as \"** DETAILED DATA NOT YET AVAILABLE **\". "
        "Those schools mostly run their own financial systems, which is likely why the state file only has "
        "their totals. Their "
        "spending counts toward agency totals but can't be broken down by vendor.\n"
        f"- **No vendor.** About {share.get(NO_VENDOR, 0):.0%} of dollars have a blank vendor, which is "
        "mostly payroll.\n"
        f"- **People are never named.** Payments to individuals ({share.get(INDIVIDUAL, 0):.1%} of dollars) "
        "are grouped as \"Individual or small payee (name withheld)\". The rule errs toward hiding, so some "
        "small businesses end up in that group too.\n"
        "- **FY2025 file format.** Most FY2025 monthly files were exported as padded text with no quotes, "
        "so commas inside values (\"Travel, Personal Vehicle\") break a normal CSV reader and would silently "
        "drop about 1 in 6 rows. The pipeline splits those files on their fixed column positions instead, "
        "and skips the stray SQL*Plus error lines a few of them contain.\n"
        "- **Partial years.** Year-over-year comparisons for a partial year only use the months both "
        "years have.\n")
    return "\n".join(out)
